/* Builds the two copies of Ghana's regions and districts from tools/ghana-districts.json:
 *   app/js/ghana-districts.js   (the sign-up dropdowns)
 *   app/api/ghana-districts.php (the server's check)
 * Run: node tools/build-ghana-data.js   (after editing the JSON) */
const fs = require('fs');
const path = require('path');
const src = JSON.parse(fs.readFileSync(path.join(__dirname, 'ghana-districts.json'), 'utf8'));
const OTHER = 'Other (not listed)';
const regions = Object.keys(src).filter(k => !k.startsWith('_'));
let total = 0;
const data = {};
for (const r of regions) { data[r] = src[r].slice().sort((a, b) => a.localeCompare(b)); total += data[r].length; }
console.log(regions.length + ' regions, ' + total + ' districts');
for (const r of regions) console.log('  ' + r + ': ' + data[r].length);
if (regions.length !== 16) throw new Error('expected 16 regions');

const js = '/* Generated by tools/build-ghana-data.js from tools/ghana-districts.json. Do not edit by hand. */\n' +
  '(function (g) { g.GH_DISTRICTS = ' + JSON.stringify(data) + '; g.GH_DISTRICT_OTHER = ' + JSON.stringify(OTHER) + '; })(window);\n';
fs.writeFileSync(path.join(__dirname, '..', 'app', 'js', 'ghana-districts.js'), js);

// A PHP single-quoted string (JSON object syntax is not valid PHP, so write real array syntax).
const q = x => "'" + String(x).split('\\').join('\\\\').split("'").join("\\'") + "'";
const php = '<?php\n/* Generated by tools/build-ghana-data.js from tools/ghana-districts.json. Do not edit by hand.\n * Returns [region => [districts]]; "' + OTHER + '" is always accepted as a district. */\n' +
  'return [\n' + regions.map(r => '  ' + q(r) + ' => [' + data[r].map(q).join(', ') + '],').join('\n') + '\n];\n';
fs.writeFileSync(path.join(__dirname, '..', 'app', 'api', 'ghana-districts.php'), php);
console.log('written');
