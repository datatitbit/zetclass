#!/usr/bin/env node
/* ============================================================
 * make-config.js — creates app/api/config.local.php, the file that holds
 * your server's SECRETS (database password, session-signing key, and your
 * developer login for zetclass.com/admin).
 *
 * Run it on YOUR computer, in this project folder:
 *
 *     node tools/make-config.js
 *
 * It asks a few questions, then writes the file. Passwords you type are not
 * shown on screen, and nothing is sent anywhere. Afterwards, upload the file
 * to the same folder as index.php on the server (cPanel > File Manager >
 * .../api/). The file is listed in .gitignore so it can never be committed.
 * ============================================================ */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const readline = require('readline');

const OUT = path.join(__dirname, '..', 'app', 'api', 'config.local.php');
const interactive = process.stdin.isTTY;

// --- tiny prompt helpers (no dependencies) ---
let rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: !!interactive });
const lineQueue = [];            // used when input is piped (tests)
let lineWaiters = [];
if (!interactive) {
  rl.on('line', (l) => { const w = lineWaiters.shift(); if (w) w(l); else lineQueue.push(l); });
}
function ask(question) {
  return new Promise((resolve) => {
    if (!interactive) {
      process.stdout.write(question);
      if (lineQueue.length) { const l = lineQueue.shift(); process.stdout.write('\n'); return resolve(l); }
      return lineWaiters.push((l) => { process.stdout.write('\n'); resolve(l); });
    }
    rl.question(question, resolve);
  });
}
function askHidden(question) {
  if (!interactive) return ask(question);
  return new Promise((resolve) => {
    process.stdout.write(question);
    rl.pause();
    const stdin = process.stdin;
    stdin.setRawMode(true); stdin.resume(); stdin.setEncoding('utf8');
    let buf = '';
    const onData = (ch) => {
      for (const c of ch) {
        if (c === '\r' || c === '\n') { stdin.setRawMode(false); stdin.removeListener('data', onData); process.stdout.write('\n'); rl.resume(); return resolve(buf); }
        if (c === '\u0003') { process.stdout.write('\n'); process.exit(1); }           // Ctrl+C
        if (c === '\u007f' || c === '\b') { buf = buf.slice(0, -1); continue; }          // backspace
        buf += c;
      }
    };
    stdin.on('data', onData);
  });
}
const phpStr = (s) => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";

(async () => {
  console.log('\nZetclass — create the server secrets file\n');
  console.log('You will need the MySQL database details from cPanel (MySQL® Databases).\n');
  if (fs.existsSync(OUT)) {
    const a = (await ask('A config.local.php already exists here. Replace it? (type yes to replace): ')).trim().toLowerCase();
    if (a !== 'yes') { console.log('Left it alone. Nothing changed.'); process.exit(0); }
  }
  const dbName = (await ask('Database name   (e.g. zetrekzh_zetclass): ')).trim();
  const dbUser = (await ask('Database user   (e.g. zetrekzh_zetclass_user): ')).trim();
  const dbPass = await askHidden('Database password (hidden): ');
  if (!dbName || !dbUser || !dbPass) { console.error('\nDatabase name, user and password are all required.'); process.exit(1); }

  const devUser = (await ask('\nDeveloper username for zetclass.com/admin (letters/numbers, e.g. zurk): ')).trim();
  if (!/^[A-Za-z0-9._-]{3,40}$/.test(devUser)) { console.error('\nUse 3–40 letters, numbers, dots, dashes or underscores.'); process.exit(1); }
  const p1 = await askHidden('Developer password (at least 12 characters, hidden): ');
  const p2 = await askHidden('Type it again to confirm (hidden): ');
  if (p1 !== p2) { console.error('\nThe two passwords did not match. Nothing was written.'); process.exit(1); }
  if (p1.length < 12) { console.error('\nPlease use at least 12 characters (a few random words is fine). Nothing was written.'); process.exit(1); }
  const notify = (await ask('\nEmail me when a school signs up? Enter your email, or press Enter to skip: ')).trim();
  if (notify && !/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(notify)) { console.error('\nThat does not look like an email address. Nothing was written.'); process.exit(1); }

  const appSecret = crypto.randomBytes(32).toString('hex');
  const salt = crypto.randomBytes(16).toString('hex');
  const hash = crypto.pbkdf2Sync(p1, Buffer.from(salt, 'hex'), 100000, 32, 'sha256').toString('hex'); // same recipe as auth.php

  const php = `<?php
/* Generated by tools/make-config.js on ${new Date().toISOString().slice(0, 10)}.
 * SECRET — do not email, commit or share this file. */
return [
    'DB_DRIVER'  => 'mysql',
    'MYSQL_HOST' => 'localhost',
    'MYSQL_NAME' => ${phpStr(dbName)},
    'MYSQL_USER' => ${phpStr(dbUser)},
    'MYSQL_PASS' => ${phpStr(dbPass)},

    'APP_SECRET' => ${phpStr(appSecret)},

    'PLATFORM_ADMIN' => [
        'username' => ${phpStr(devUser)},
        'salt'     => ${phpStr(salt)},
        'hash'     => ${phpStr(hash)},
    ],
${notify ? `\n    'NOTIFY_EMAIL' => ${phpStr(notify)},\n` : ''}];
`;
  fs.writeFileSync(OUT, php, { mode: 0o600 });
  console.log('\nDone. Wrote: ' + OUT);
  console.log('\nNext: upload that file to the same folder as index.php on the server');
  console.log('(cPanel > File Manager > your site > api). Keep a private copy somewhere safe;');
  console.log('your developer password cannot be recovered from it, only replaced.\n');
  process.exit(0);
})();
